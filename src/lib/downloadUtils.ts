import { Plan } from '../types';

/**
 * Sanitizes a string for use as a safe, descriptive filename
 */
export function sanitizeFilename(name: string, fallback = 'plan'): string {
  const cleaned = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 45);
  return cleaned || fallback;
}

/**
 * Formats full plan into clean Markdown with complete metadata
 */
export function generateMarkdown(plan: Plan): string {
  const createdDate = new Date(plan.createdAt).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  return `# Action Plan: ${plan.requirement}

> **Timeframe:** ${plan.startDate} to ${plan.endDate}  
> **Weekly Commitment:** ${plan.hoursPerWeek} hours/week  
> **Generated on:** ${createdDate}  
> **Powered by:** Agentic Planner (Researcher → Planner → Reviewer)

---

${plan.content.trim()}
`;
}

/**
 * Formats full plan into plain text with ASCII borders
 */
export function generatePlainText(plan: Plan): string {
  const createdDate = new Date(plan.createdAt).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const divider = '='.repeat(70);
  const subDivider = '-'.repeat(70);

  // Strip simple markdown symbols for plain text view
  const cleanContent = plan.content
    .replace(/^#{1,6}\s+/gm, '') // remove headings
    .replace(/\*\*(.*?)\*\*/g, '$1') // remove bold
    .replace(/\*(.*?)\*/g, '$1') // remove italics
    .replace(/`([^`]+)`/g, '$1'); // remove inline code

  return `${divider}
ACTION PLAN: ${plan.requirement.toUpperCase()}
${divider}

Timeframe:          ${plan.startDate} to ${plan.endDate}
Weekly Commitment:  ${plan.hoursPerWeek} hours per week
Generated on:       ${createdDate}
Agent Architecture: Researcher → Planner → Reviewer

${subDivider}
PLAN DETAILS
${subDivider}

${cleanContent.trim()}

${divider}
Generated by Agentic Planner
${divider}
`;
}

