/**
 * Downloads a string as a file using a reliable link click mechanism
 */
export function triggerFileDownload(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.setAttribute('download', filename);
  anchor.style.display = 'none';
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);

  // Keep blob URL around long enough for the browser download subsystem
  setTimeout(() => {
    URL.revokeObjectURL(url);
  }, 2000);
}

/**
 * Main export function supporting markdown, text, or HTML
 */
export function downloadPlan(plan: Plan, format: 'md' | 'txt' | 'html' = 'md'): string {
  const baseName = sanitizeFilename(plan.requirement, `plan-${plan.id.slice(0, 8)}`);

  switch (format) {
    case 'md': {
      const filename = `${baseName}.md`;
      const content = generateMarkdown(plan);
      triggerFileDownload(content, filename, 'text/markdown');
      return filename;
    }
    case 'txt': {
      const filename = `${baseName}.txt`;
      const content = generatePlainText(plan);
      triggerFileDownload(content, filename, 'text/plain');
      return filename;
    }
    case 'html': {
      const filename = `${baseName}.html`;
      const content = generateHtmlDocument(plan);
      triggerFileDownload(content, filename, 'text/html');
      return filename;
    }
  }
}
